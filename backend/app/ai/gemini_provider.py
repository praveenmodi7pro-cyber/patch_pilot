import json
import httpx
from typing import Dict, List, Optional, Any
from app.ai.base import (
    BaseAIProvider,
    DiagnosisFinding,
    RootCauseAnalysisResult,
    GeneratedPatchResult,
)
from app.ai.prompts import (
    SYSTEM_DIAGNOSIS_PROMPT,
    USER_DIAGNOSIS_TEMPLATE,
    SYSTEM_PATCH_PROMPT,
    USER_PATCH_TEMPLATE,
)


class GeminiProvider(BaseAIProvider):
    """Google Gemini AI Provider integration using REST API."""

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-pro"):
        super().__init__(model_name=model_name, api_key=api_key)
        self.endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent"

    async def _call_gemini(self, system_instruction: str, user_prompt: str) -> str:
        headers = {"Content-Type": "application/json"}
        params = {"key": self.api_key}
        payload = {
            "system_instruction": {
                "parts": [{"text": system_instruction}]
            },
            "contents": [
                {
                    "parts": [{"text": user_prompt}]
                }
            ],
            "generationConfig": {
                "response_mime_type": "application/json",
                "temperature": 0.2,
            }
        }

        async with httpx.AsyncClient(timeout=60.0) as client:
            response = await client.post(self.endpoint, params=params, json=payload, headers=headers)
            response.raise_for_status()
            data = response.json()
            candidates = data.get("candidates", [])
            if not candidates:
                raise ValueError("No response candidate returned by Gemini API")
            text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
            return text

    async def analyze_root_cause(
        self,
        repository_context: Dict[str, Any],
        static_findings: List[Dict[str, Any]],
        test_failures: Optional[List[Dict[str, Any]]] = None,
    ) -> RootCauseAnalysisResult:
        user_prompt = USER_DIAGNOSIS_TEMPLATE.format(
            primary_language=repository_context.get("primary_language", "python"),
            manifest_files=", ".join(repository_context.get("manifest_files", [])),
            test_files=", ".join(repository_context.get("test_files", [])),
            static_findings_json=json.dumps(static_findings[:20], indent=2),
            source_files_context=json.dumps(repository_context.get("source_samples", {}), indent=2)[:4000],
            test_failures_context=json.dumps(test_failures or [], indent=2)[:3000],
        )

        raw_text = await self._call_gemini(SYSTEM_DIAGNOSIS_PROMPT, user_prompt)
        parsed = json.loads(raw_text)

        findings = []
        for f in parsed.get("findings", []):
            findings.append(DiagnosisFinding(**f))

        return RootCauseAnalysisResult(
            findings=findings,
            summary=parsed.get("summary", "Gemini analysis completed."),
            tokens_used=parsed.get("usage", {}).get("total_tokens", 800),
            model=self.model_name,
        )

    async def generate_patch(
        self,
        bug_finding: DiagnosisFinding,
        file_contents: Dict[str, str],
        previous_feedback: Optional[str] = None,
    ) -> GeneratedPatchResult:
        file_content = file_contents.get(bug_finding.file_path, "")
        user_prompt = USER_PATCH_TEMPLATE.format(
            title=bug_finding.title,
            category=bug_finding.category,
            file_path=bug_finding.file_path,
            line_number=bug_finding.line_number or 1,
            root_cause=bug_finding.root_cause,
            suggested_fix=bug_finding.suggested_fix,
            previous_feedback=previous_feedback or "None",
            file_content=file_content[:6000],
        )

        raw_text = await self._call_gemini(SYSTEM_PATCH_PROMPT, user_prompt)
        parsed = json.loads(raw_text)

        return GeneratedPatchResult(
            patch_content=parsed.get("patch_content", ""),
            files_changed=parsed.get("files_changed", [bug_finding.file_path]),
            explanation=parsed.get("explanation", "Patch generated by Gemini."),
            tokens_used=parsed.get("usage", {}).get("total_tokens", 600),
            model=self.model_name,
        )

